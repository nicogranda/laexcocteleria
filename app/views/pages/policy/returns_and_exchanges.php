<h1 class="principal">Our Returns & Exchange Policy</h1>
<main class="container">
<p>At Maleta Chic, we want you to love your purchase. If you’re not completely satisfied, we offer easy returns and exchanges to ensure your happiness.</p>

<ul>
    <li><strong>Returns:</strong> You can return items within <strong>7 days</strong> from the purchase (shipment) date.</li>
    <li><strong>Exchanges:</strong> You can exchange jewelry within <strong>15 days</strong> from the purchase (shipment) date. Watches can be exchanged within <strong>15 days</strong> from the purchase (shipment) date for online orders.</li>
</ul>

<h2>Conditions for Returns and Exchanges:</h2>
<ul>
    <li>Items must be in their <strong>original condition</strong> with all packaging, instructions, and paperwork.</li>
    <li><strong>Watches</strong> must include all original links.</li>
    <li><strong>Exclusions:</strong> We cannot accept returns or exchanges on <strong>special order watches</strong>, <strong>gift cards</strong>, <strong>ear piercing earrings</strong>, <strong>custom designs</strong>, or <strong>protection plan replacement merchandise</strong>.</li>
    <li><strong>Progressive Leasing:</strong> Merchandise purchased through Progressive Leasing cannot be exchanged.</li>
</ul>

<h2>Refund Process:</h2>
<p>Refunds will be credited to the original payment method:</p>
<ul>
    <li><strong>Credit/Debit Cards:</strong> The same account will be credited.</li>
    <li><strong>Check:</strong> A refund check will be issued and mailed within <strong>21 days</strong>.</li>
    <li><strong>Cash:</strong> If the refund amount exceeds <strong>$500</strong>, a refund check will be issued and mailed within <strong>21 days</strong>.</li>
    <li><strong>Gift Card:</strong> Refunds will be given in the form of a new gift card. <strong>Gift cards cannot be returned</strong> (except where required by law).</li>
    <li><strong>Trade-Ins:</strong> You will receive either your original trade-in item or similar merchandise.</li>
</ul>

<h2>Merchandise with a Gift Receipt:</h2>
<p>Items with a gift receipt can be exchanged for merchandise or returned for a gift card within <strong>30 days</strong> from the purchase date. <strong>Excludes Progressive Leasing purchases.</strong></p>

<h2>For Online Orders:</h2>
<p>Refunds will be credited to your original payment method, excluding shipping charges. Processing time for refunds is typically <strong>5 business days</strong>. Refunds will reflect on your account depending on your financial institution, usually within <strong>5-7 business days</strong>.</p>

<h2>Free Return Shipping:</h2>
<p>For your convenience, we offer a <strong>FREE pre-printed shipping label</strong> for returns by mail. Simply click below to begin your return process!</p>

<p>If you prefer not to use the free return shipping, you will find a pre-printed return label and address label on your packing slip. These labels should be affixed to the top corners of your return package. Please note that these are not pre-paid labels, and you will need to purchase shipping from a carrier like <strong>UPS, USPS, or FedEx</strong>. A <strong>Return Reason</strong> column is provided on your packing slip to indicate the reason for your return.</p>

<h2>Important:</h2>
<p>All returns must include the <strong>Packing Slip</strong> and any original documents included with your order. Returns will be inspected by our <strong>Quality Assurance</strong> team before processing a refund.</p>

<p>Thank you for shopping at Maleta Chic! We are dedicated to providing you with exceptional customer service and ensuring your satisfaction.</p>
</main>
